const displayNamesCache = new Map<string, Intl.DisplayNames | null>();

function getDisplayNames(locale: string): Intl.DisplayNames | null {
  if (displayNamesCache.has(locale)) return displayNamesCache.get(locale) ?? null;
  let names: Intl.DisplayNames | null = null;
  if (typeof Intl !== 'undefined' && typeof Intl.DisplayNames !== 'undefined') {
    try {
      names = new Intl.DisplayNames([locale, 'en'], { type: 'region', fallback: 'none' });
    } catch {
      names = null;
    }
  }
  displayNamesCache.set(locale, names);
  return names;
}

/** Localized country name for a code; falls back to the code itself. */
export function countryName(code: string, locale: string): string {
  return getDisplayNames(locale)?.of(code) ?? code;
}

/** All countries with localized names + default currency, sorted by name. */
export function getCountries(locale: string): CountryOption[] {
  return Object.entries(COUNTRY_CURRENCIES)
    .map(([code, currency]) => ({ code, name: countryName(code, locale), currency }))
    .sort((a, b) => a.name.localeCompare(b.name, locale));
}

/** Default currency for a country code, or undefined if unknown. */
export function currencyForCountry(code: string): string | undefined {
  return COUNTRY_CURRENCIES[code.toUpperCase()];
}
